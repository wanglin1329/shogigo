const CENTER = { files: [7, 3], ranks: [3, 7] } as const

/** One piece on 5五 (or `sq`) with its moves. */
function alone(glyph: string, name: string, sq = '55', crop: Diagram['crop'] = CENTER): Diagram {
  const pieces: Pieces = { [sq]: glyph }
  return {
    pieces,
    crop,
    marks: moveMarks(pieces, sq),
    caption: name,
    alt: `${name}の動き。点のあるマスへ動ける`,
  }
}

